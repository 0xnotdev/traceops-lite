from traceops.core.schemas import (
    ParsedTrace,
    GeneratedTest,
    FailureType,
)

from textwrap import dedent

import json
import logging

logger = logging.getLogger(__name__)


def generate_test(
    parsed: ParsedTrace,
) -> GeneratedTest:
    """
    Convert a ParsedTrace into a DeepEval
    regression test file.
    """

    test_id = parsed.trace_id[:8]

    file_name = (
        f"test_regression_{test_id}.py"
    )

    metric_code = _select_metric(
        parsed.failure_type
    )

    chunks_repr = json.dumps(
        parsed.retrieved_chunks,
        indent=8,
    )

    query_repr = json.dumps(
        parsed.query
    )

    output_repr = json.dumps(
        parsed.llm_response
    )

    sources_repr = json.dumps(
        parsed.sources,
        indent=8,
    )

    test_content = dedent(
        f"""\
        # AUTO-GENERATED REGRESSION TEST
        # ----------------------------------------
        # Source trace: {parsed.trace_id}
        # Failure type: {parsed.failure_type.value}
        # Model: {parsed.model}
        # Generated by: TraceOps Lite
        #
        # This file was automatically generated
        # from a production failure report.
        #
        # DO NOT EDIT MANUALLY
        # ----------------------------------------

        import pytest

        from deepeval import assert_test
        from deepeval.test_case import LLMTestCase

        {metric_code["imports"]}


        @pytest.mark.regression
        def test_regression_{test_id}():
            \"\"\"
            Regression test generated from
            production trace:

            {parsed.trace_id}

            Failure type:
            {parsed.failure_type.value}
            \"\"\"

            test_case = LLMTestCase(
                input={query_repr},
                actual_output={output_repr},
                retrieval_context={chunks_repr},
            )

            {metric_code["metric_init"]}

            assert_test(
                test_case,
                [{metric_code["metric_name"]}],
            )


        # ---- Metadata ----------------------------------

        TRACE_ID = "{parsed.trace_id}"

        FAILURE_TYPE = "{parsed.failure_type.value}"

        MODEL = "{parsed.model}"

        SOURCES = {sources_repr}
        """
    )

    logger.info(
        f"Generated regression test: "
        f"{file_name}"
    )

    return GeneratedTest(
        trace_id=parsed.trace_id,
        failure_type=parsed.failure_type,
        test_file_content=test_content,
        test_file_name=file_name,
    )


def _select_metric(
    failure_type: FailureType,
) -> dict:
    """
    Map failure types to the most appropriate
    DeepEval metric.
    """

    if failure_type == FailureType.HALLUCINATION:
        return {
            "imports": (
                "from deepeval.metrics "
                "import HallucinationMetric"
            ),
            "metric_init": (
                "metric = "
                "HallucinationMetric("
                "threshold=0.5)"
            ),
            "metric_name": "metric",
        }

    elif failure_type in (
        FailureType.BAD_RETRIEVAL,
        FailureType.STALE_CONTEXT,
    ):
        return {
            "imports": (
                "from deepeval.metrics "
                "import FaithfulnessMetric"
            ),
            "metric_init": (
                "metric = "
                "FaithfulnessMetric("
                "threshold=0.8)"
            ),
            "metric_name": "metric",
        }

    elif failure_type == FailureType.POOR_REASONING:
        return {
            "imports": (
                "from deepeval.metrics "
                "import AnswerRelevancyMetric"
            ),
            "metric_init": (
                "metric = "
                "AnswerRelevancyMetric("
                "threshold=0.7)"
            ),
            "metric_name": "metric",
        }

    else:
        return {
            "imports": (
                "from deepeval.metrics "
                "import AnswerRelevancyMetric"
            ),
            "metric_init": (
                "metric = "
                "AnswerRelevancyMetric("
                "threshold=0.7)"
            ),
            "metric_name": "metric",
        }